export function translateStatus(text) {
  // 替换 [状态] 为图标 + 翻译，并添加 data-status 属性用于悬浮提示
  return text.replace(/\[([^\]]+)\]/g, (match, key) => {
    const icon = statusIcons[key]
    const trans = statusTranslations[key] || key
    const _desc = statusDescriptions[key] || trans
    if (icon) {
      return `<img src="./Buf/${icon}" class="status-icon" alt="${trans}" data-status="${key}"><span class="status-name-translated" data-status="${key}">${trans}</span>`
    }
    return `<span class="status-name-translated" data-status="${key}">${trans}</span>`
  })
}
